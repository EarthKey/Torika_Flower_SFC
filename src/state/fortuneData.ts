const TORIKA_NAME = '酉花（トリカ）'

// 日付を数値シードにする（例: 2026-07-19 → 20260719）。実行中に日をまたいでも反映される
function todaySeed(now = new Date()): number {
  return now.getFullYear() * 10000 + (now.getMonth() + 1) * 100 + now.getDate()
}

// 2026-07-22 テストプレイ用の一時措置（本人依頼）: 同じ日は同じ結果になる仕様のため、
// 大吉が出た日は他の結果（末吉等）を確認できない。trueの間は毎回ランダムなシードにして
// 開くたびに結果が変わるようにする。確認が終わったらfalseに戻すこと
const TEST_RANDOM_FORTUNE = true

// 今日の花占いをトリカの独白（会話ウインドウ用の行）として返す。
// 花と運勢は別々の素数で混ぜて、日ごとの組み合わせが単純な循環にならないようにする。
// 2026-07-19改修（本人指示）: 花名は2倍・運勢結果は3倍で拡大表示し、詳細な結果は次のページへ分離
export function fortuneLines(): DialogueLine[] {
  const seed = TEST_RANDOM_FORTUNE ? Math.floor(Math.random() * 1_000_000) : todaySeed()
  const flower = FLOWERS[(seed * 13 + 7) % FLOWERS.length]
  const luck = LUCKS[(seed * 31 + 3) % LUCKS.length]
  const line = (face: number, text: string, emScale?: number): DialogueLine => ({
    speaker: 'torika',
    name: TORIKA_NAME,
    face,
    text,
    emScale,
  })
  return [
    line(2, 'よーし、今日の花占い、いってみよう！　水盤にお花を浮かべて……。'),
    line(3, `今日のお花は――**『${flower.name}』**！`, 2),
    line(flower.face, flower.text),
    line(1, 'そして、今日の運勢は……？'),
    line(luck.face, `**『${luck.label}』**！`, 3),
    line(luck.faceAfter ?? luck.face, luck.labelSuffix ? `${luck.labelSuffix}　${luck.text}` : luck.text),
  ]
}
